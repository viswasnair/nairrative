-- ── new_releases ──────────────────────────────────────────────────────────────
-- Populated by the scheduled Edge Function (supabase/functions/check-releases).

create table public.new_releases (
  id              uuid primary key default gen_random_uuid(),
  title           text not null,
  author          text not null,
  series          text,
  published_date  text,
  description     text,
  cover_url       text,
  google_books_id text unique,
  detected_at     timestamptz default now(),
  dismissed       boolean default false
);

alter table public.new_releases enable row level security;

create policy "public read"
  on public.new_releases for select to public using (true);

create policy "authenticated write"
  on public.new_releases for all to public using (auth.role() = 'authenticated');
